/**
 * 全站统一的播放速度，单位是秒。
 *
 * 为什么要单独一个文件：这些数字以前是各实验台各写各的，
 * 结果同类素材在不同页面速度差一倍 —— 半音阶每音 0.24 秒、音阶 0.28 秒、
 * 五声 0.3 秒、和弦 0.8 秒。听起来不像同一个站，
 * 而且快的那些（每秒 4 个音以上）根本来不及听清音高。
 *
 * 命名按**素材类型**而不是意大利语术语 —— 速度术语只该用在真正的
 * 速度标记上（第 19 节要讲），拿它们给播放参数命名是另一回事，容易误导。
 *
 * 这些值对应的大致速度：
 *   single 0.9s ≈ 每分钟 67 个音   听一个音的音色
 *   chord  0.85s ≈ 每分钟 71 个和弦 听和声色彩
 *   melody 0.48s ≈ 每分钟 125 拍   旋律的正常步子
 *   scale  0.40s ≈ 每分钟 150 个音 音阶，能听清每一个
 *   run    0.30s ≈ 每分钟 200 个音 半音阶、走句这类快速经过
 *   ornament 0.09s ≈ 每分钟 667 个音 装饰音，本来就是快的
 */

export const TEMPO = {
  single: 0.9,
  chord: 0.85,
  melody: 0.48,
  scale: 0.4,
  run: 0.3,
  ornament: 0.09,
};

/** 音阶类素材的默认参数：音与音之间留一点点重叠，听起来是连的，不是断的。 */
export const SCALE_ARGS = { gap: TEMPO.scale, duration: 0.5, level: 0.24 };

/** 和弦进行的默认参数。 */
export const CHORD_ARGS = { gap: TEMPO.chord, duration: 0.8, level: 0.17 };
